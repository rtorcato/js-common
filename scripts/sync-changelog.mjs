// Builds the docs site's changelog page from **GitHub Releases**, not from
// CHANGELOG.md.
//
// LOCAL PATCH of a shared @rtorcato/repo-tooling asset (the canonical version,
// `repo-tooling copy docusaurus-sync-changelog`, copies the root CHANGELOG.md
// verbatim). Delete this file and re-copy the shared one once
// https://github.com/rtorcato/repo-tooling/issues/411 lands.
//
// Why the fork: this repo drops @semantic-release/git (see release.config.mjs —
// the code-scanning-main ruleset rejects the release commit with GH013), so
// nothing commits CHANGELOG.md back to main. It is frozen at 2.8.2 and will
// stay there. Copying it would publish a changelog that silently stops at the
// last release that ran with the git plugin, under a heading that claims it is
// generated by semantic-release. GitHub Releases cannot go stale the same way:
// @semantic-release/github writes them from the same notes that used to build
// CHANGELOG.md, so concatenating their bodies reproduces the old page exactly.
//
// Releases only go back to v1.2.0. Pre-1.2.0 history lives in CHANGELOG.md in
// the repo, which the footer links to.

import { readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..')
const repo = process.env.GITHUB_REPOSITORY ?? 'rtorcato/js-common'
const target = resolve(repoRoot, process.env.CHANGELOG_TARGET ?? 'apps/docs/docs/changelog.md')

const frontmatter = `---
title: Changelog
description: Release notes, generated by semantic-release and published to GitHub Releases.
---

`

const footer = (note) =>
	`\n\n---\n\n${note}Every entry above is generated by semantic-release and published to [GitHub Releases](https://github.com/${repo}/releases). Versions before v1.2.0 predate those releases and are recorded in [CHANGELOG.md](https://github.com/${repo}/blob/main/CHANGELOG.md).\n`

async function fetchReleases() {
	const headers = { Accept: 'application/vnd.github+json' }
	// Optional: lifts the 60/hr unauthenticated rate limit. CI passes it; local
	// builds work fine without it at this repo's release count.
	const token = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN
	if (token) headers.Authorization = `Bearer ${token}`

	const res = await fetch(`https://api.github.com/repos/${repo}/releases?per_page=100`, { headers })
	if (!res.ok) throw new Error(`GitHub API ${res.status} ${res.statusText}`)
	return res.json()
}

function render(releases) {
	// The API does not guarantee date order, and a release body already carries
	// its own version heading and date — so sort here and emit bodies verbatim.
	const sorted = releases
		.filter((r) => !r.draft && r.body?.trim())
		.sort((a, b) => new Date(b.published_at) - new Date(a.published_at))

	if (sorted.length === 0) throw new Error('no releases with a body')
	return sorted.map((r) => r.body.trim()).join('\n\n')
}

let body
try {
	body = render(await fetchReleases()) + footer('')
	console.log(`sync-changelog: built from ${repo} GitHub Releases`)
} catch (error) {
	// Never fail the docs build on a network blip — fall back to the frozen file
	// and say so on the page rather than shipping a silently truncated one.
	console.warn(`sync-changelog: ${error.message} — falling back to CHANGELOG.md`)
	try {
		body =
			readFileSync(resolve(repoRoot, 'CHANGELOG.md'), 'utf8').trim() +
			footer(
				'**This page was built from the repository CHANGELOG.md because GitHub Releases could not be reached, and may be out of date.** '
			)
	} catch {
		body = `# Changelog\n\nSee [GitHub Releases](https://github.com/${repo}/releases).\n`
	}
}

mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, frontmatter + body)
console.log(`sync-changelog: wrote ${target}`)
